-- Docker startup scripts often run in CDB$ROOT. Put objects in FREEPDB1
-- as SYSTEM so the Flask app can connect with SYSTEM / FREEPDB1.
BEGIN
    IF SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1' THEN
        EXECUTE IMMEDIATE 'ALTER SESSION SET CONTAINER = FREEPDB1';
    END IF;
END;
/

ALTER SESSION SET CURRENT_SCHEMA = SYSTEM;

-- ==========================================
-- SPRINT 1 TABLES
-- ==========================================
CREATE TABLE Users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    first_name VARCHAR2(50),
    last_name VARCHAR2(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- SPRINT 2 NEW TABLES & RELATIONSHIPS
-- ==========================================
CREATE TABLE Restaurants (
    restaurant_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    location VARCHAR2(255)
);

CREATE TABLE MenuItems (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    description VARCHAR2(255),
    price NUMBER(8, 2) NOT NULL,
    category VARCHAR2(50),
    is_available NUMBER(1) DEFAULT 1,
    restaurant_id NUMBER NOT NULL,
    CONSTRAINT fk_menu_restaurant FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id)
);

CREATE TABLE Orders (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    restaurant_id NUMBER NOT NULL,
    status VARCHAR2(50) DEFAULT 'Pending',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES Users(user_id),
    CONSTRAINT fk_order_restaurant FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id)
);

CREATE TABLE Cart (
    cart_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    quantity NUMBER DEFAULT 1,
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES Users(user_id),
    CONSTRAINT fk_cart_item FOREIGN KEY (item_id) REFERENCES MenuItems(item_id)
);

