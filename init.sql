-- Docker startup scripts often run in CDB$ROOT. Put objects in FREEPDB1
-- as SYSTEM so the Flask app can connect with SYSTEM / FREEPDB1.
BEGIN
    IF SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1' THEN
        EXECUTE IMMEDIATE 'ALTER SESSION SET CONTAINER = FREEPDB1';
    END IF;
END;
/

ALTER SESSION SET CURRENT_SCHEMA = SYSTEM;

-- ==========================================
-- SPRINT 1 TABLES
-- ==========================================
CREATE TABLE Users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    first_name VARCHAR2(50),
    last_name VARCHAR2(50),
    role VARCHAR2(20) DEFAULT 'customer' NOT NULL,
    restaurant_id NUMBER,
    CONSTRAINT chk_user_role CHECK (role IN ('customer', 'staff')),
    CONSTRAINT chk_staff_restaurant CHECK (role <> 'staff' OR restaurant_id IS NOT NULL),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- SPRINT 2 NEW TABLES & RELATIONSHIPS
-- ==========================================
CREATE TABLE Restaurants (
    restaurant_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    location VARCHAR2(255)
);

ALTER TABLE Users ADD CONSTRAINT fk_user_restaurant
    FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id);

CREATE TABLE MenuItems (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    description VARCHAR2(255),
    price NUMBER(8, 2) NOT NULL,
    category VARCHAR2(50),
    is_available NUMBER(1) DEFAULT 1,
    restaurant_id NUMBER NOT NULL,
    CONSTRAINT fk_menu_restaurant FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id)
);

CREATE TABLE Orders (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    restaurant_id NUMBER NOT NULL,
    total NUMBER(8, 2) DEFAULT 0 NOT NULL,
    status VARCHAR2(50) DEFAULT 'Pending',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES Users(user_id),
    CONSTRAINT fk_order_restaurant FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id)
);

CREATE TABLE OrderItems (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    quantity NUMBER NOT NULL,
    price_at_order NUMBER(8, 2) NOT NULL,
    CONSTRAINT fk_oi_order FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    CONSTRAINT fk_oi_item FOREIGN KEY (item_id) REFERENCES MenuItems(item_id),
    CONSTRAINT chk_oi_quantity CHECK (quantity > 0)
);

CREATE TABLE Cart (
    cart_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    quantity NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES Users(user_id),
    CONSTRAINT fk_cart_item FOREIGN KEY (item_id) REFERENCES MenuItems(item_id),
    CONSTRAINT uq_cart_user_item UNIQUE (user_id, item_id),
    CONSTRAINT chk_cart_quantity CHECK (quantity > 0)
);

CREATE TABLE Reviews (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    order_id NUMBER NOT NULL,
    rating NUMBER(1) NOT NULL,
    comments VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_review_user FOREIGN KEY (user_id) REFERENCES Users(user_id),
    CONSTRAINT fk_review_order FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    CONSTRAINT uq_review_user_order UNIQUE (user_id, order_id),
    CONSTRAINT chk_review_rating CHECK (rating BETWEEN 1 AND 5)
);

